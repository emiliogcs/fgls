test_that("simulate_serial reproduces the PG26 Table 1 design", {
  sim <- simulate_serial(500, seed = 1)
  expect_equal(dim(sim), c(500L, 2L))
  u <- attr(sim, "u")
  e <- attr(sim, "e")
  expect_equal(u[1], e[1])
  expect_equal(u[2:500], 0.8 * u[1:499] + e[2:500])
  expect_equal(sim$y, 1 + sim$x + u)
  expect_identical(simulate_serial(50, seed = 3), simulate_serial(50, seed = 3))
  ma <- simulate_serial(100, ar = numeric(0), ma = 0.5, gamma = 0, seed = 2)
  ue <- attr(ma, "e")
  expect_equal(attr(ma, "u")[-1], ue[-1] + 0.5 * ue[-100])
})

test_that("simulate_hetero and simulate_combined", {
  h <- simulate_hetero(200, skedastic = "log2", n_extra = 3, extra_corr = 0.5, seed = 1)
  expect_named(h, c("y", "x", "w1", "w2", "w3"))
  expect_true(all(h$x >= 1 & h$x <= 4))
  expect_equal(attr(h, "info")$v, log(h$x)^2)
  hc <- simulate_hetero(10, skedastic = function(x) x^3, seed = 1)
  expect_equal(attr(hc, "info")$v, hc$x^3)
  expect_error(simulate_hetero(10, skedastic = "nope"), class = "fgls_error_input")
  c1 <- simulate_combined(200, ar = c(1.34, -0.42), skedastic = "exp", seed = 1)
  expect_named(c1, c("y", "x", "w"))
  expect_equal(c1$x, c1$w)
  c2 <- simulate_combined(200, driver = "mixture", gamma = 0.5, seed = 1)
  expect_false(isTRUE(all.equal(c2$x, c2$w)))
  expect_equal(c2$y, 1 + c2$x + attr(c2, "u"))
})

test_that("simulate_predictive aligns y_{t+2} with x_t", {
  p <- simulate_predictive(300, theta = -0.4, seed = 5)
  expect_equal(nrow(p), 300L)
  expect_equal(p$y, 1 + p$x + attr(p, "u"))
  ee <- attr(p, "e")
  expect_equal(attr(p, "u")[-1], ee[-1] - 0.4 * ee[-300])
})
